create table if not exists public.clothing_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  category text not null,
  color text not null,
  season text,
  image_url text,
  is_favorite boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.outfits (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  top_id bigint,
  bottom_id bigint,
  dress_id bigint,
  outerwear_id bigint,
  shoes_id bigint,
  accessory_id bigint,
  bag_id bigint,
  outfit_image_url text,
  note text,
  created_at timestamptz not null default now(),
  constraint outfits_top_id_fkey foreign key (top_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_bottom_id_fkey foreign key (bottom_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_dress_id_fkey foreign key (dress_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_outerwear_id_fkey foreign key (outerwear_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_shoes_id_fkey foreign key (shoes_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_accessory_id_fkey foreign key (accessory_id)
    references public.clothing_items(id) on delete set null,
  constraint outfits_bag_id_fkey foreign key (bag_id)
    references public.clothing_items(id) on delete set null
);

create index if not exists clothing_items_user_id_idx
  on public.clothing_items(user_id);
create index if not exists outfits_user_id_idx
  on public.outfits(user_id);

alter table public.clothing_items enable row level security;
alter table public.outfits enable row level security;

grant select, insert, update, delete on public.clothing_items to authenticated;
grant select, insert, update, delete on public.outfits to authenticated;
grant usage, select on sequence public.clothing_items_id_seq to authenticated;
grant usage, select on sequence public.outfits_id_seq to authenticated;

drop policy if exists "Users manage their clothing items" on public.clothing_items;
create policy "Users manage their clothing items"
  on public.clothing_items
  for all
  to authenticated
  using ((select auth.uid())::text = user_id::text)
  with check ((select auth.uid())::text = user_id::text);

drop policy if exists "Users manage their outfits" on public.outfits;
create policy "Users manage their outfits"
  on public.outfits
  for all
  to authenticated
  using ((select auth.uid())::text = user_id::text)
  with check ((select auth.uid())::text = user_id::text);

create or replace function public.ensure_outfit_items_belong_to_user()
returns trigger
language plpgsql
as $$
begin
  if exists (
    select 1
    from unnest(array[
      new.top_id,
      new.bottom_id,
      new.dress_id,
      new.outerwear_id,
      new.shoes_id,
      new.accessory_id,
      new.bag_id
    ]) as selected(item_id)
    left join public.clothing_items as item on item.id = selected.item_id
    where selected.item_id is not null
      and item.user_id::text is distinct from new.user_id::text
  ) then
    raise exception 'Outfit items must belong to the same user';
  end if;

  return new;
end;
$$;

drop trigger if exists ensure_outfit_items_belong_to_user on public.outfits;
create trigger ensure_outfit_items_belong_to_user
  before insert or update on public.outfits
  for each row execute function public.ensure_outfit_items_belong_to_user();

insert into storage.buckets (id, name, public)
values ('clothing-images', 'clothing-images', false)
on conflict (id) do update set public = false;

drop policy if exists "Users upload their clothing photos" on storage.objects;
create policy "Users upload their clothing photos"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'clothing-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "Users view their clothing photos" on storage.objects;
create policy "Users view their clothing photos"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'clothing-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "Users delete their clothing photos" on storage.objects;
create policy "Users delete their clothing photos"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'clothing-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
